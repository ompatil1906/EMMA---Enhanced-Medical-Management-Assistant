"""Citation validator (Day 6).

Validates that citations in a generated answer actually reference retrieved
chunks from the active practice. Never trusts citations generated by the LLM
without verification.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.domain.retrieval import RetrievedChunk


@dataclass(frozen=True)
class CitationValidationResult:
    """Result of validating citations against retrieved chunks."""

    valid_citations: list[str]  # chunk IDs that passed validation
    invalid_citations: list[str]  # chunk IDs that failed validation
    reasons: dict[str, str]  # chunk_id -> reason for invalidity


def validate_citations(
    *,
    cited_chunk_ids: list[str],
    retrieved_chunks: list[RetrievedChunk],
    practice_id: str,
) -> CitationValidationResult:
    """Validate that every cited chunk ID exists in the retrieved results,
    belongs to the active practice, and has non-empty content.

    Accepts both full chunk IDs and 1-based numeric citation markers
    (e.g. "1", "2") that reference retrieved_chunks by position.

    Returns a CitationValidationResult with valid and invalid citation IDs.
    """
    retrieved_by_id: dict[str, RetrievedChunk] = {
        chunk.chunk_id: chunk for chunk in retrieved_chunks
    }

    valid: list[str] = []
    invalid: list[str] = []
    reasons: dict[str, str] = {}

    for cited in cited_chunk_ids:
        # Resolve the citation: either a direct chunk_id or a 1-based
        # numeric marker into the retrieved chunks list.
        chunk: RetrievedChunk | None = None
        if cited.isdigit() and 1 <= int(cited) <= len(retrieved_chunks):
            chunk = retrieved_chunks[int(cited) - 1]
        else:
            chunk = retrieved_by_id.get(cited)

        if chunk is None:
            invalid.append(cited)
            reasons[cited] = "chunk not found in retrieval results"
            continue

        if chunk.practice_id != practice_id:
            invalid.append(cited)
            reasons[cited] = "chunk does not belong to the requesting practice"
            continue

        if not chunk.content or not chunk.content.strip():
            invalid.append(cited)
            reasons[cited] = "chunk content is empty"
            continue

        valid.append(chunk.chunk_id)

    return CitationValidationResult(
        valid_citations=valid,
        invalid_citations=invalid,
        reasons=reasons,
    )


__all__ = ["CitationValidationResult", "validate_citations"]
