@pytest.mark.asyncio
async def test_summary_is_submitted_once_at_call_end() -> None:
    harness = await make_pipeline(
        responses={"I'd like an appointment for Tuesday morning": _appointment()},
        caller=CallerIdentity(first_name="Sarah", last_name="Jenkins", reason="Book Appointment"),
    )
    try:
        await run_turn(harness, "I'd like an appointment for Tuesday morning")
    finally:
        await close(harness)

    assert len(harness.practice.call_records) == 1
    assert len(harness.practice.summaries) == 1
    submitted = harness.practice.summaries[0]
    payload = submitted["summary_payload"]
    assert payload["headline"] == "Appointment request — Sarah J."
    assert payload["caller"]["firstName"] == "Sarah"
    assert payload["tasks"][0]["requestType"] == "appointment-request"
    assert submitted["call_id"] == "call-eval-record"
    assert submitted["idempotency_key"]


@pytest.mark.asyncio
async def test_emergency_call_submits_nothing() -> None:
    harness = await make_pipeline(responses={})
    try:
        await run_turn(harness, "I have chest pain")
    finally:
        await close(harness)
    assert harness.practice.summaries == []


@pytest.mark.asyncio
async def test_summary_can_be_disabled() -> None:
    harness = await make_pipeline(responses={}, settings_overrides={"CALL_SUMMARY_ENABLED": False})
    try:
        await run_turn(harness, "thanks")
    finally:
        await close(harness)
    assert harness.practice.summaries == []


@pytest.mark.asyncio
async def test_slow_summary_submission_cannot_delay_teardown() -> None:
    harness = await make_pipeline(responses={}, settings_overrides={"CALL_SUMMARY_TIMEOUT": 0.05})
    harness.practice.summary_delay_seconds = 5.0
    try:
        await run_turn(harness, "thanks")
    finally:
        started = asyncio.get_running_loop().time()
        await close(harness)
        elapsed = asyncio.get_running_loop().time() - started
    assert elapsed < 1.5, f"teardown blocked for {elapsed:.2f}s"
