"""Day 19: deterministic call summary + end-of-call submission.

Hard rules under test:

* the summary is derived from server state (form, captured requests, statuses) —
  never invented, never model-generated by default;
* it is submitted exactly once, idempotently, under a bounded timeout;
* an emergency-guarded call submits **nothing** (zero administrative actions);
* a summary can never delay or break teardown, and a failed submission never
  becomes a spoken or persisted claim of success.
"""

from __future__ import annotations

import asyncio

import pytest

from app.domain.conversation import ConversationState, Speaker, TurnStatus
from app.domain.llm import InterpretationResult, RequestDetail
from app.services.call_summary import build_call_summary
from app.services.caller_identity import CallerIdentity
from app.services.conversation.conversation_controller import ConversationController
from tests.evaluation.day9 import close, make_pipeline, run_turn


def _appointment() -> InterpretationResult:
    return InterpretationResult(
        intent="appointment-request",
        requests=[
            RequestDetail(
                request_type="appointment-request",
                details={"preferred_date": "Tuesday", "preferred_time": "morning"},
                missing_fields=[],
                source_quotes=["Tuesday"],
            )
        ],
    )


def _state_with_confirmed_request() -> ConversationState:
    controller = ConversationController(ConversationState())
    controller.handle_interpretation(_appointment())
    controller.handle_confirmation(confirmed=True, request_type="appointment-request")
    controller.mark_submitting("appointment-request", turn_id="turn-1", idempotency_key="key-1")
    controller.handle_backend_success(request_type="appointment-request", idempotency_key="key-1")
    state = controller.state
    state.add_turn(
        turn_id="turn-caller",
        speaker=Speaker.CALLER,
        content="I'd like an appointment for Tuesday morning",
        status=TurnStatus.COMPLETED,
        correlation_id=1,
    )
    state.add_turn(
        turn_id="turn-assistant",
        speaker=Speaker.ASSISTANT,
        content="Thank you. I've passed your request to the practice team.",
        status=TurnStatus.COMPLETED,
        correlation_id="turn-caller",
    )
    return state


def test_summary_describes_the_form_the_requests_and_the_tasks() -> None:
    caller = CallerIdentity(
        first_name="Sarah", last_name="Jenkins", mobile="+44 7700 900077", reason="Book Appointment"
    )
    summary = build_call_summary(
        conversation=_state_with_confirmed_request(),
        caller=caller,
        outcome="completed",
        started_at=100.0,
        now=142.0,
    )

    assert summary.headline == "Appointment request — Sarah J."
    assert summary.outcome == "completed"
    assert summary.duration_seconds == 42
    assert summary.caller == {
        "firstName": "Sarah",
        "lastName": "Jenkins",
        "mobile": "+44 7700 900077",
        "reason": "Book Appointment",
    }
    text = "\n".join(summary.bullets)
    assert "Caller: Sarah J. (mobile ending 077)" in text
    assert "Reason given on the intake form: Book Appointment" in text
    assert "Appointment request (submitted)" in text
    assert "Confirmed by the practice system: 1" in text
    # The task carries the operational payload the practice needs.
    assert summary.tasks[0]["type"] == "appointment"
    assert summary.tasks[0]["status"] == "submitted"
    assert (
        summary.tasks[0]["title"]
        == "Appointment request — preferred date: Tuesday; preferred time: morning"
    )
    assert summary.tasks[0]["details"] == {
        "preferred_date": "Tuesday",
        "preferred_time": "morning",
    }


def test_summary_without_a_form_or_requests_is_still_honest() -> None:
    summary = build_call_summary(conversation=ConversationState(), caller=None, outcome="completed")
    text = "\n".join(summary.bullets)
    assert summary.headline == "General enquiry — Unnamed caller"
    assert "name not captured" in text.lower()
    assert "No administrative request was captured." in text
    assert summary.tasks == ()
    assert summary.caller == {}


def test_emergency_outcome_is_recorded_without_tasks() -> None:
    summary = build_call_summary(
        conversation=ConversationState(),
        caller=CallerIdentity(first_name="Sam"),
        outcome="emergency",
    )
    text = "\n".join(summary.bullets)
    assert "Emergency guard matched" in text
    assert summary.tasks == ()


def test_transcript_excerpt_is_opt_in_and_capped() -> None:
    state = _state_with_confirmed_request()
    without = build_call_summary(conversation=state, caller=None, outcome="completed")
    assert without.transcript_excerpt is None

    with_excerpt = build_call_summary(
        conversation=state, caller=None, outcome="completed", include_transcript=True
    )
    assert with_excerpt.transcript_excerpt is not None
    assert len(with_excerpt.transcript_excerpt) <= 1200


def test_payload_is_json_safe() -> None:
    import json

    payload = build_call_summary(
        conversation=_state_with_confirmed_request(),
        caller=CallerIdentity(first_name="Sarah"),
        outcome="completed",
        started_at=0.0,
        now=1.0,
    ).to_payload()
    encoded = json.dumps(payload)
    assert '"headline"' in encoded
    assert payload["turns"] >= 1


